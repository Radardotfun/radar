// Builds extension/src/lib/slot-calendar.js: [slot, unixTime] samples across Solana history,
// so time -> slot needs no RPC round trips (getBlockTime is heavily rate-limited publicly).
import fs from 'node:fs';
const RPC = 'https://api.mainnet-beta.solana.com';
const call = async (method, params) => {
  for (let i = 0; i < 8; i++) {
    const r = await fetch(RPC, { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ jsonrpc: '2.0', id: 1, method, params }) });
    if (r.status === 429) { await new Promise((s) => setTimeout(s, 2000 * (i + 1))); continue; }
    const j = await r.json();
    if (j.error) { const e = new Error(j.error.message); e.code = j.error.code; throw e; }
    return j.result;
  }
  throw new Error('rate limited');
};
const tip = await call('getSlot', [{ commitment: 'finalized' }]);
const points = [];
for (let s = 150_000_000; s < tip; s += 2_000_000) {
  for (let k = 0; k < 20; k++) {
    try { const t = await call('getBlockTime', [s + k]); if (t) { points.push([s + k, t]); break; } } catch (e) { if (![-32007, -32009, -32004].includes(e.code)) throw e; }
  }
  await new Promise((r) => setTimeout(r, 900));
}
const out = `// Generated by test/calendar.mjs on ${new Date().toISOString().slice(0, 10)}: [slot, unix seconds] samples.\n// Lets the bundle scan turn a timestamp into a slot without rate-limited RPC calls.\nexport const SLOT_CALENDAR = ${JSON.stringify(points)};\n`;
fs.writeFileSync('extension/src/lib/slot-calendar.js', out);
console.log(points.length, 'points', points[0], points.at(-1));
